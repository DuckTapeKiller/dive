// Builds skills/books/global-book-search.js from a checkout of the Global Book
// Search Obsidian plugin, so Dive's book_search tool runs the plugin's own
// search code: every source, the StoryGraph login, the ISBN gap-filling, the
// field-by-field merge and the cooldowns for blocked sources.
//
//   node scripts/build-book-sources.mjs [path/to/global-book-search]
//
// The path defaults to ../global-book-search. The output is committed, so
// Dive builds and runs without the plugin folder; run this again after the
// plugin changes. Obsidian's runtime is replaced by skills/books/obsidian.js
// (written here, listing the names the bundled modules import) and
// skills/books/obsidian-adapter.js (hand-written: requestUrl, DOMParser).
import esbuild from "esbuild";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pluginDir = path.resolve(
  process.argv[2] || path.join(root, "..", "global-book-search"),
);
const outDir = path.join(root, "skills", "books");

const manifest = JSON.parse(
  fs.readFileSync(path.join(pluginDir, "manifest.json"), "utf8"),
);
let commit = "";
try {
  commit = execFileSync(
    "git",
    ["-C", pluginDir, "rev-parse", "--short", "HEAD"],
    {
      encoding: "utf8",
    },
  ).trim();
} catch {
  commit = "unknown";
}

// Every name the bundled modules import from "obsidian", collected as esbuild
// loads them, so obsidian.js can export each one explicitly.
const obsidianNames = new Set();
const IMPORT_RE = /import\s*\{([^}]*)\}\s*from\s*["']obsidian["']/g;

const obsidianShim = {
  name: "obsidian-shim",
  setup(build) {
    build.onResolve({ filter: /^obsidian$/ }, () => ({
      path: "./obsidian.js",
      external: true,
    }));
    build.onLoad({ filter: /\.ts$/ }, (args) => {
      const source = fs.readFileSync(args.path, "utf8");
      for (const match of source.matchAll(IMPORT_RE)) {
        for (const part of match[1].split(",")) {
          const name = part.trim();
          if (!name || name.startsWith("type ")) continue;
          obsidianNames.add(name.split(/\s+as\s+/)[0].trim());
        }
      }
      return null; // let esbuild load it as usual
    });
  },
};

const entry = `
export {
  globalSearch,
  enrichBookByISBN,
  enrichFromIsbn,
} from "./src/apis/global_search";
export { factoryServiceProvider } from "./src/apis/base_api";
export { storyGraphLogin, cleanCookieValue } from "./src/apis/storygraph_api";
export { ProviderBlockedError } from "./src/utils/http";
export { DEFAULT_SETTINGS } from "./src/settings/settings";
export { GLOBAL_SEARCH_SOURCE_LABELS } from "./src/constants";
`;

const banner = `// GENERATED by scripts/build-book-sources.mjs from Global Book Search
// ${manifest.version} (${commit}). Do not edit: change the plugin and rebuild.
// Source: https://github.com/DuckTapeKiller/global-book-search
/* eslint-disable */
const { DOMParser, window } = require("./obsidian-adapter.js");`;

const result = await esbuild.build({
  stdin: {
    contents: entry,
    resolveDir: pluginDir,
    sourcefile: "dive-book-search-entry.ts",
    loader: "ts",
  },
  tsconfig: path.join(pluginDir, "tsconfig.json"),
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  treeShaking: true,
  minify: false,
  legalComments: "inline",
  banner: { js: banner },
  outfile: path.join(outDir, "global-book-search.js"),
  plugins: [obsidianShim],
  logLevel: "warning",
  metafile: true,
});

const names = [...obsidianNames].sort();
const shim = `"use strict";
// GENERATED by scripts/build-book-sources.mjs: the names Global Book Search
// ${manifest.version} imports from "obsidian", taken from the Node adapter.
const { obsidian } = require("./obsidian-adapter.js");

module.exports = {
${names.map((name) => `  ${name}: obsidian.${name},`).join("\n")}
};
`;
fs.writeFileSync(path.join(outDir, "obsidian.js"), shim);

const bytes = fs.statSync(path.join(outDir, "global-book-search.js")).size;
const inputs = Object.keys(result.metafile.inputs).length;
console.log(
  `Global Book Search ${manifest.version} (${commit}): ${inputs} modules, ${(bytes / 1024).toFixed(0)} KB; obsidian names: ${names.join(", ")}`,
);
